#!/usr/bin/env python3
"""Rebuilds the core once per deliberate bug and requires the verification to
fail. A bug that no check catches is a hole in the testbench (or a bug that
cannot change behaviour, which then needs an argument for why).

Each variant runs: rv32ui compliance in lockstep, then a fixed random batch.
Results go to docs/bug_injection_results.md."""
import os
import re
import subprocess
import sys
import time

BUGS = {
    "BUG_NO_FWD_EXMEM_RS1": "no EX/MEM -> EX forwarding on rs1",
    "BUG_NO_FWD_EXMEM_RS2": "no EX/MEM -> EX forwarding on rs2",
    "BUG_NO_FWD_MEMWB_RS1": "no MEM/WB -> EX forwarding on rs1",
    "BUG_NO_FWD_MEMWB_RS2": "no MEM/WB -> EX forwarding on rs2",
    "BUG_FWD_PRIORITY": "older MEM/WB value wins over newer EX/MEM value",
    "BUG_FWD_X0": "forwards a write to x0 as if it were real",
    "BUG_NO_LOAD_USE_STALL": "no load-use stall",
    "BUG_NO_WB_BYPASS": "register file read misses the value being written back",
    "BUG_FLUSH_ONE": "redirect flushes only IF/ID, the instruction in ID still runs",
    "BUG_X0_WRITABLE": "writes to x0 land in x1",
    "BUG_SLT_UNSIGNED": "slt compares unsigned",
    "BUG_SRA_LOGICAL": "sra shifts in zeros",
    "BUG_BLTU_SIGNED": "bltu compares signed",
    "BUG_JALR_NO_CLEAR_LSB": "jalr keeps bit 0 of the target",
    "BUG_LB_ZERO_EXTEND": "lb zero-extends",
    "BUG_SH_MASK": "sh to the upper half writes the wrong byte lanes",
    "BUG_NO_STORE_BYPASS": "load right after a store to the same word reads stale RAM",
    "BUG_MEPC_NEXT": "mepc gets pc+4 instead of the trapping pc",
}

RANDOM_COUNT = int(os.environ.get("CAMPAIGN_RANDOM", "50"))


def run(cmd, timeout=1800):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout)


def first_failure(out):
    for line in out.splitlines():
        if line.startswith("FAIL"):
            return line[5:].strip()
    return ""


def main():
    os.makedirs("build/campaign", exist_ok=True)
    r = run("make -s build/gen && ./build/gen --out build/campaign --count %d --len 2000 --seed 777" % RANDOM_COUNT)
    if r.returncode:
        print(r.stdout, r.stderr)
        sys.exit(1)
    run("make -s -C tests")
    rows = []
    caught = 0
    for bug, desc in BUGS.items():
        t0 = time.time()
        b = run("make -s sim BUG=%s" % bug)
        if b.returncode:
            print(bug, "build failed")
            print(b.stdout[-2000:], b.stderr[-2000:])
            sys.exit(1)
        sim = "./build/obj_%s/Vtb_top" % bug
        c = run("%s --quiet tests/build/*.bin" % sim)
        how, detail = "", ""
        if c.returncode:
            how, detail = "rv32ui", first_failure(c.stdout)
        else:
            rr = run("%s --quiet build/campaign/*.bin" % sim)
            if rr.returncode:
                how, detail = "random", first_failure(rr.stdout)
        ok = bool(how)
        caught += ok
        detail = re.sub(r"^\S+/", "", detail)
        rows.append((bug, desc, how or "NOT CAUGHT", detail))
        print("%-24s %-10s %5.0fs  %s" % (bug, how or "MISSED", time.time() - t0, detail[:90]), flush=True)
        run("rm -rf build/obj_%s" % bug)

    with open("docs/bug_injection_results.md", "w") as f:
        f.write("# Bug injection results\n\n")
        f.write("Generated by `scripts/bug_campaign.py`. Each row rebuilds the core with one bug and runs the\n")
        f.write("rv32ui suite in lockstep, then %d random programs (seed 777).\n\n" % RANDOM_COUNT)
        f.write("Caught: **%d of %d**\n\n" % (caught, len(BUGS)))
        f.write("| Define | Bug | Caught by | First failure |\n|---|---|---|---|\n")
        for bug, desc, how, detail in rows:
            f.write("| `%s` | %s | %s | %s |\n" % (bug, desc, how, detail.replace("|", "/")[:120]))
    print("caught %d of %d" % (caught, len(BUGS)))
    sys.exit(0 if caught == len(BUGS) else 1)


if __name__ == "__main__":
    main()
